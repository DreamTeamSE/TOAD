# -*- coding: utf-8 -*-
"""
train_sam3.py  —  Finetune SAM 3 on TOAD histology segmentation

Strategy
--------
- Use build_sam3_image_model(eval_mode=False) — the full image model with Hungarian matcher.
- Freeze the ViT backbone (32-layer, 1024-dim) to keep GPU memory and wall-time manageable.
- Finetune: geometry encoder, transformer encoder+decoder, segmentation head.
- One image per step (batch_size=1); all tissue classes in that image are prompted together.
- Loss: Dice + BCE on matched (pred, GT) mask pairs, computed directly from model output.
- Box prompts come from the SEKO-predicted mask (not GT) — see ToadSam3Dataset —
  so training sees the same (imperfect) prompt distribution as inference on
  images with no ground truth. GT still supplies the loss/DICE target.
- SEKO's checkpoint was retrained with osteophyte pixels merged into cartilage,
  so it only ever outputs 5 classes (background + 4 tissue types). GT masks are
  remapped the same way (osteophyte label 5 -> cartilage label 2) before use,
  so the loss target stays consistent with what SEKO can actually prompt for.
  Osteophyte is intentionally not tracked as its own class right now.

Inputs (from train_seko.csv, generated by src/utils/cache_seko_masks.py)
--------------------------------------------------------------------------
  image_path     : RGB .tif, any size  → resized to 1008×1008
  mask_path      : uint8 .tif, values 0-5 (TOAD label schema) — GT; label 5
                    (osteophyte) is remapped to 2 (cartilage) on load
  seko_mask_path : uint8 .tif, values 0-4 — SEKO prediction, used as box-prompt source
  stain          : HE | SafO | TolBlu  (unused during training, kept for stratified splits)

Usage
-----
  conda activate seko-sam3
  python src/utils/cache_seko_masks.py   # once, to populate train_seko.csv
  python src/train_sam3.py
  python src/train_sam3.py --ckpt models/sam3_checkpoint.pt --epochs 30 --lr 1e-4
"""

